using System;
using System.Collections.Generic;
using System.Data;
using System.IO;
using System.Linq;
using System.Text;
using System.Windows.Forms;
using FuturePath.Business;
using FuturePath.Entities;

namespace FuturePath.Presentation
{
    public class ReportCentreForm : BaseForm
    {
        private readonly ComboBox reportBox = new ComboBox { DropDownStyle = ComboBoxStyle.DropDownList };
        private readonly DateTimePicker fromDate = new DateTimePicker { Format = DateTimePickerFormat.Short, Value = DateTime.Today.AddYears(-1) };
        private readonly DateTimePicker toDate = new DateTimePicker { Format = DateTimePickerFormat.Short, Value = DateTime.Today };
        private readonly ComboBox facultyBox = new ComboBox();
        private readonly ComboBox outcomeBox = new ComboBox { DropDownStyle = ComboBoxStyle.DropDownList };
        private readonly TextBox preview = new TextBox { Multiline = true, ReadOnly = true, ScrollBars = ScrollBars.Vertical, Width = 580, Height = 200 };

        private string html = "";   // the finished report as a web page (used by Export and Print)

        public ReportCentreForm() : base("Report Centre")
        {
            reportBox.Items.AddRange(new object[] { "Degree Interest and Eligibility Report", "Learners Not Currently Eligible Exception Report" });
            outcomeBox.Items.AddRange(new object[] { "All outcomes", Outcomes.StrongMatch, Outcomes.PossibleMatch,
                                                      Outcomes.NotCurrentlyEligible, Outcomes.MoreInformationNeeded });
            outcomeBox.SelectedIndex = 0;

            // The faculty list starts with "All faculties" (its ID is 0, which means "no faculty filter").
            // "All faculties" is chosen later, in OnLoad, once the drop-down has received its items.
            var faculties = new List<Faculty> { new Faculty { FacultyID = 0, FacultyName = "All faculties" } };
            faculties.AddRange(AdvisingController.GetFaculties());
            Bind(facultyBox, faculties, "FacultyName", "FacultyID");

            AddRow("Report *", reportBox);
            AddRow("Date from", fromDate);
            AddRow("Date to", toDate);
            AddRow("Faculty", facultyBox);
            AddRow("Outcome", outcomeBox);
            AddWide(NewButton("Generate", (s, e) => Generate()));
            AddWide(new Label { Text = "The date, faculty and outcome filters apply to the Degree Interest and Eligibility Report only.", AutoSize = true });
            AddWide(preview);

            AddButton("Back", (s, e) => GoBack());
            AddButton("Print", (s, e) => Print());
            AddButton("Export", (s, e) => Export());
        }

        // Runs when the screen is about to be shown. By now the faculty drop-down has its items,
        // so we can safely choose the first one ("All faculties").
        protected override void OnLoad(EventArgs e)
        {
            base.OnLoad(e);
            if (facultyBox.Items.Count > 0 && facultyBox.SelectedIndex < 0) facultyBox.SelectedIndex = 0;
        }

        // Runs when the user clicks Generate.
        private void Generate()
        {
            ShowError("");
            if (reportBox.SelectedIndex < 0) { ShowError("Please choose a report."); return; }
            if (fromDate.Value.Date > toDate.Value.Date) { ShowError("The 'Date from' must not be after the 'Date to'."); return; }

            var text = new StringBuilder();

            if (reportBox.SelectedIndex == 0)
            {
                // Report 2. "All outcomes" (index 0) means no outcome filter, which the Business layer expects as "".
                string outcome = outcomeBox.SelectedIndex <= 0 ? "" : outcomeBox.Text;
                DegreeInterestReport? report = ReportService.BuildDegreeInterestReport(
                    fromDate.Value.Date, toDate.Value.Date, SelectedId(facultyBox), outcome);
                if (report == null) { ShowError("You do not have access to this report."); return; }

                text.AppendLine("DEGREE INTEREST AND ELIGIBILITY REPORT");
                text.AppendLine("Reporting period: " + report.FromDate.ToString("dd MMM yyyy") + " to " + report.ToDate.ToString("dd MMM yyyy"));
                text.AppendLine("Filter: " + report.FilterText);
                text.AppendLine("Generated by: " + report.GeneratedBy);
                text.AppendLine("Date generated: " + report.GeneratedOn.ToString("dd MMM yyyy HH:mm"));
                text.AppendLine();
                AppendTable(text, "Faculty and degree selection", report.FacultyDegree);
                AppendTable(text, "Eligibility outcomes", report.OutcomeSummary);
                AppendTable(text, "Common subject gaps", report.SubjectGaps);
                AppendTable(text, "Common mark gaps", report.MarkGaps);
                AppendTable(text, "Most requested funding categories", report.FundingCategories);
                text.AppendLine("REPORT SUMMARY");
                text.AppendLine("  Total learners included: " + report.TotalLearners);
                text.AppendLine("  Most selected faculty: " + report.MostSelectedFaculty);
                text.AppendLine("  Most selected degree: " + report.MostSelectedDegree);
                text.AppendLine("  Most common outcome: " + report.MostCommonOutcome);
                html = ExportService.BuildDegreeInterestHtml(report);
            }
            else
            {
                // Report 3.
                ExceptionReportData? report = ReportService.BuildExceptionReport();
                if (report == null) { ShowError("You do not have access to this report."); return; }

                text.AppendLine("LEARNERS NOT CURRENTLY ELIGIBLE EXCEPTION REPORT");
                text.AppendLine("Date generated: " + report.GeneratedOn.ToString("dd MMM yyyy HH:mm"));
                text.AppendLine();
                AppendTable(text, "Exception summary", report.OutcomeSummary);
                AppendTable(text, "Reasons for exception", report.ReasonSummary);
                AppendTable(text, "Exception details", report.Details);
                html = ExportService.BuildExceptionHtml(report);
            }

            text.AppendLine();
            text.AppendLine(ExportService.Disclaimer);
            preview.Text = text.ToString();
        }

        // Writes a table into the on-screen text: a heading, a line of column names, then one line per row.
        private static void AppendTable(StringBuilder text, string heading, DataTable table)
        {
            text.AppendLine(heading.ToUpper());
            if (table.Rows.Count == 0)
            {
                text.AppendLine("  None");
                text.AppendLine();
                return;
            }
            text.AppendLine("  " + string.Join(" | ", table.Columns.Cast<DataColumn>().Select(c => c.ColumnName)));
            foreach (DataRow row in table.Rows)
                text.AppendLine("  " + string.Join(" | ", row.ItemArray.Select(value => value?.ToString())));
            text.AppendLine();
        }

        // Runs when the user clicks Export: saves the report as a web page file.
        private void Export()
        {
            if (html == "") { ShowError("Please generate a report first."); return; }

            using (var dialog = new SaveFileDialog())
            {
                dialog.Filter = "Web page (*.html)|*.html";
                dialog.FileName = reportBox.Text.Replace(" ", "") + "_" + DateTime.Now.ToString("yyyyMMdd") + ".html";
                if (dialog.ShowDialog() != DialogResult.OK) return;

                try
                {
                    ExportService.SaveFile(dialog.FileName, html);
                    MessageBox.Show("The report was saved to:\n" + dialog.FileName);   // confirmation message
                }
                catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
                {
                    ShowError("The file could not be saved. Please choose a different folder.");
                }
            }
        }

        // Runs when the user clicks Print: opens the report in the web browser (then Ctrl+P prints it).
        private void Print()
        {
            if (html == "") { ShowError("Please generate a report first."); return; }
            ExportService.OpenInBrowser(html);
            MessageBox.Show("The report has opened in your web browser. Press Ctrl+P there to print it or save it as a PDF.");
        }
    }
}